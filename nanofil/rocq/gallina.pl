% A checked module as a Gallina term, for a proof about one program
% (Panics.v, docs/formal.md's Campaign 7). Reads `nanofil outcomes`
% output on stdin and prints a Rocq file that defines NAME_term, the
% module's `module(Items)` term as Term.v's [term], context items
% dropped. Transport.v's decode_module turns it into the module.
%
%   (cd src && ../bin/nanofil -O outcomes FILE.ir </dev/null) |
%     swipl rocq/gallina.pl NAME SOURCE [CHECKER] >rocq/theories/NAMECode.v
%
% The output is a fixture: rocq/programs.sh regenerates it and fails
% when nanofil's checked module has changed.

:- initialization(main, main).

main :-
    % The terms' atoms are UTF-8, whatever the locale (a Nix build has none).
    set_stream(user_input, encoding(utf8)),
    current_prolog_flag(argv, [Name, Source|Rest]),
    ( Rest = [Checker] -> true ; Checker = 'rocq/programs.sh' ),
    read_term(user_input, T, []),
    (   T = module(Items0)
    ->  exclude(is_context, Items0, Items)
    ;   format(user_error, "gallina.pl: expected module(Items), got ~q~n", [T]),
        halt(1)
    ),
    format("(** The checked module nanofil -O makes of ~w, as a [term].~n", [Source]),
    format("    Generated by rocq/gallina.pl; ~w checks it is~n", [Checker]),
    format("    current. Do not edit. *)~n~n"),
    format("From Stdlib Require Import String ZArith List Ascii.~n"),
    format("From Nanofil Require Import Term.~n"),
    format("Import ListNotations.~n"),
    format("Open Scope string_scope.~n"),
    format("Open Scope Z_scope.~n~n"),
    format("(** The one-character atom with code n. *)~n"),
    format("Definition chr (n : nat) : term := TAtom (String (ascii_of_nat n) EmptyString).~n~n"),
    format("(** The module term. *)~n"),
    format("Definition ~w_term : term :=~n  TApp \"module\" [TList [~n", [Name]),
    items(Items),
    format("  ]].~n").

is_context(context(_, _)).

% A function with one block per line group and one instruction per
% line, so the file reads as the module does; other items on one line.
item(func(N, L, R, Ps, Bs)) :- !,
    format("TApp \"func\" ["), list([N, L, R, Ps]), format(";~n      TList ["),
    blocks(Bs), format("]]").
item(I) :- gallina(I).

blocks([]).
blocks([block(L, Phis, Is, J)|Bs]) :-
    format("~n        TApp \"block\" ["), gallina(L), format("; "), gallina(Phis),
    format(";~n          TList ["), insts(Is), format("];~n          "), gallina(J), format("]"),
    ( Bs == [] -> true ; format(";") ),
    blocks(Bs).

insts([]).
insts([I|Is]) :-
    format("~n            "), gallina(I), ( Is == [] -> true ; format(";") ), insts(Is).

items([]).
items([I|Is]) :-
    format("    "), item(I),
    ( Is == [] -> nl ; format(";~n") ),
    items(Is).

gallina(T) :- integer(T), !,
    ( T < 0 -> format("TInt (~d)", [T]) ; format("TInt ~d", [T]) ).
gallina(T) :- T == [], !, format("TList []").
gallina(T) :- is_list(T), !,
    format("TList ["), list(T), format("]").
gallina(T) :- atom(T), !, atom_gallina(T).
gallina(T) :- compound(T), !,
    compound_name_arguments(T, F, As),
    format("TApp "), string_lit(F), format(" ["), list(As), format("]").

list([]).
list([X|Xs]) :- gallina(X), ( Xs == [] -> true ; format("; ") ), list(Xs).

atom_gallina(A) :-
    atom_codes(A, Cs),
    (   Cs = [C], C >= 128, C =< 255
    ->  % Term.v's char_code reads a character from 128 to 255 as its
        % two UTF-8 bytes, as the term reader gives it.
        B1 is 192 + C // 64, B2 is 128 + C mod 64,
        format("TAtom (String (ascii_of_nat ~d) (String (ascii_of_nat ~d) EmptyString))", [B1, B2])
    ;   Cs = [C], \+ printable(C)
    ->  format("(chr ~d)", [C])
    ;   maplist(printable, Cs)
    ->  format("TAtom "), string_lit(A)
    ;   format(user_error, "gallina.pl: atom ~q has unprintable characters~n", [A]),
        halt(1)
    ).

printable(C) :- C >= 32, C =< 126.

string_lit(A) :-
    atom_codes(A, Cs),
    format("\""),
    forall(member(C, Cs), ( C =:= 0'" -> format("\"\"") ; format("~c", [C]) )),
    format("\"").
