#!/usr/bin/env bash
# Check that the constant-time proofs still describe the checked IR
# nanofil generates for their C fixtures.
#
#   FILCC=.../clang MODEL=.../nanofil-model rocq/scripts/programs.sh            # check
#   FILCC=.../clang MODEL=.../nanofil-model rocq/scripts/programs.sh --update   # rewrite generated fixtures
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
src="$here/../../src"
nanofil="$here/../../bin/nanofil"
: "${FILCC:?set FILCC to a filcc clang}"
MODEL="${MODEL:-$here/../nanofil-model}"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

mode="${1:-}"

sync_file() {
  local generated="$1" target="$2" source="$3"
  local base
  base=$(basename "$target")
  if [ "$mode" = --update ]; then
    cp "$generated" "$target"
  else
    diff -u "$target" "$generated"
    echo "$base matches nanofil -O of $source"
  fi
}

# Legacy Prolog-term fixture (used by CtLt.v).
check_term_fixture() {
  local source="$1" prefix="$2" target="$3"
  local base
  base=$(basename "$target")
  (cd "$src" && "$nanofil" cc-ir "$here/../../$source" </dev/null) >"$work/$prefix.ir"
  (cd "$src" && "$nanofil" -O outcomes "$work/$prefix.ir" </dev/null) | grep '^module(' \
    | swipl "$here/gallina.pl" "$prefix" "$source" >"$work/$base"
  sync_file "$work/$base" "$target" "$source"
}

# Typed IRNotation fixture plus C source-hint name notations.
check_typed_fixture() {
  local source="$1" name="$2" mod_def="$3" code_target="$4" names_target="$5"
  local code_base names_base
  code_base=$(basename "$code_target")
  names_base=$(basename "$names_target")
  [ -x "$MODEL" ] || { echo "programs.sh: set MODEL to nanofil-model (not found at $MODEL)" >&2; exit 1; }
  (cd "$src" && "$nanofil" cc-ir "$here/../../$source" </dev/null) >"$work/$name.ir"
  (cd "$src" && "$nanofil" -O outcomes "$work/$name.ir" </dev/null) | grep '^module(' >"$work/$name.term"
  "$MODEL" --gallina <"$work/$name.term" >"$work/$name.rec"
  swipl "$here/glibc-code/source.pl" "$work/$name.term" >"$work/$name.src.json"
  python3 - "$here/glibc-code" "$source" "$name" "$mod_def" \
            "$work/$name.rec" "$work/$name.src.json" \
            "$work/$code_base" "$work/$names_base" << 'PY'
import json, runpy, sys
from pathlib import Path

scripts, source, name, mod_def, rec_path, src_path, code_out, names_out = sys.argv[1:]
typed = runpy.run_path(str(Path(scripts) / 'typed.py'))
names_mod = runpy.run_path(str(Path(scripts) / 'names.py'))

recs = list(typed['records'](Path(rec_path).read_text()))
defs, items = [], []
for r in recs:
    ident, body = r.identifier, r.body
    if r.is_function:
        if r.kind == 'func' and 0 < len(r.blocks) <= 64:
            body += ' {\n  ' + ';\n  '.join(r.blocks) + '\n} }'
        else:
            blks = typed['listing'](['ir_blk{ ' + b + ' }' for b in r.blocks])
            body += f' blocks ({blks}) }}' if r.kind == 'func' else f' ({blks})'
        defs.append(f'Definition {ident} : func :=\n  {body}.\n')
        items.append(f'IFunc {ident}')
    else:
        defs.append(f'Definition {ident} : item :=\n  {body}.\n')
        items.append(ident)

code_text = f'''(** The checked module nanofil -O makes of {source}, written in [IRNotation].
    Generated by rocq/scripts/programs.sh; do not edit. *)

From Stdlib Require Import String ZArith List Ascii.
From Nanofil Require Import Term Syntax IRNotation.
Import ListNotations.
Open Scope string_scope.
Open Scope Z_scope.
Open Scope list_scope.
Local Abbreviation a := TAtom.
Local Notation "'t' s" := (Tmp (TAtom s)) (at level 10, s at next level).

''' + '\n'.join(defs) + f'\nDefinition {mod_def} : module :=\n  [' + '; '.join(items) + '].\n'
Path(code_out).write_text(code_text)

facts = json.loads(Path(src_path).read_text())
names_text, _ = names_mod['name_tables'](name, facts, [])
names_text = names_text.replace(
    'The code generator reproduces this file from the capture; do not edit it.',
    'Generated by rocq/scripts/programs.sh from nanofil source hints; do not edit.',
)
Path(names_out).write_text(names_text)
PY
  sync_file "$work/$code_base" "$code_target" "$source"
  sync_file "$work/$names_base" "$names_target" "$source"
}

check_term_fixture rocq/theories/logic/ct_lt.c ctlt "$here/../theories/logic/CtLtCode.v"
check_typed_fixture rocq/theories/logic/ct_table_scan.c CtTableScan cttable_module \
  "$here/../theories/logic/CtTableScanCode.v" \
  "$here/../theories/logic/CtTableScanNames.v"
