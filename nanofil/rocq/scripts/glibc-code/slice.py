"""Slice gallina.pl output at whole-item and whole-block boundaries.

    python3 -I slice.py INPUT.v OUTDIR [hi_atexit|getopt]

Both historical profiles use this packing algorithm. Only their budgets,
definition names and presentation differ. The term lines remain unchanged.
"""
import pathlib
import re
import sys

BUDGET = 525  # lines of items or blocks in one file


def main(src, outdir, profile="hi_atexit"):
    budget = 500 if profile == "getopt" else BUDGET
    prefix = "getopt" if profile == "getopt" else "hi"
    lines = open(src, encoding="utf-8").read().split("\n")
    top = lines.index('  TApp "module" [TList [')
    end = lines.index("  ]].")
    header = lines[:top]
    # The header's lede and term comment are replaced; keep the rest.
    keep = header[header.index("From Stdlib Require Import String ZArith List Ascii."):]
    keep = [l for l in keep if l != "(** The module term. *)" and not l.startswith("Definition hi_atexit_term")]
    body = lines[top + 1:end]
    items = []
    for l in body:
        if l.startswith("    ") and not l.startswith("     "):
            items.append([l])
        else:
            items[-1].append(l)
    for it in items[:-1]:
        assert it[-1].endswith(";"), it[-1][:80]
        it[-1] = it[-1][:-1]

    # Units, in order: ("item", lines) or ("blocks", lines, owner index).
    files = []  # each: (kind, [lines of the list's elements])
    cur = []
    def flush():
        nonlocal cur
        if cur:
            files.append(("items", cur))
            cur = []
    def count(f):
        return sum(len(x) for x in f)
    for it in items:
        if len(it) <= budget:
            if count(cur) + len(it) > budget:
                flush()
            cur.append(it)
            continue
        # A function too long for a file: its blocks in files of their own,
        # after the items before it.
        flush()
        assert it[0].startswith('    TApp "func" [') and it[1] == "      TList [", it[:2]
        assert it[-1].endswith("]]"), it[-1][-20:]
        blocks = []
        for l in it[2:]:
            if l.startswith('        TApp "block" ['):
                blocks.append([l])
            else:
                blocks[-1].append(l)
        blocks[-1][-1] = blocks[-1][-1][:-2]
        for b in blocks[:-1]:
            assert b[-1].endswith(";")
            b[-1] = b[-1][:-1]
        names = []
        chunk = []
        for b in blocks:
            if profile == "getopt":
                assert len(b) <= budget
            if chunk and count(chunk) + len(b) > budget:
                files.append(("blocks", chunk))
                names.append(len(files))
                chunk = []
            chunk.append(b)
        files.append(("blocks", chunk))
        names.append(len(files))
        item = [it[0], "      TList (" + " ++ ".join(f"{prefix}_blocks_{k:02d}" for k in names) + ")]"]
        # The items file after the blocks holds the function.
        cur.append(item)
    flush()

    if profile == "getopt":
        render_getopt(files, outdir)
        return

    unit_count = re.search(r"with its (\d+) user glibc units", "\n".join(header)).group(1)
    # Which blocks files each items file names.
    n = len(files)
    for k, (kind, elems) in enumerate(files, 1):
        uses = sorted({int(w[len("hi_blocks_"):].rstrip(")]"))
                       for e in elems for l in e for w in l.replace("(", " ").split()
                       if w.startswith("hi_blocks_")}) if kind == "items" else []
        out = []
        what = "items" if kind == "items" else "blocks of one function"
        out.append(f"(** Slice {k} of {n} of the checked module nanofil -O makes of")
        out.append(f"    rocq/glibc/hi_atexit.c linked with its {unit_count} user glibc units by")
        out.append(f"    rocq/scripts/link.pl --ctors: {what}, as [term]s.")
        out.append("    Generated by rocq/glibc/hi_atexit/code.sh, which checks it is")
        out.append("    current. Do not edit. *)")
        out.append("")
        out.extend(keep[:2])
        if uses:
            out.append("From Glibc Require Import " + " ".join(f"HiAtexitCode{u:02d}" for u in uses) + ".")
        out.extend(keep[2:])
        if kind == "items":
            out.append(f"(** The items of slice {k}. *)")
            out.append(f"Definition hi_items_{k:02d} : list term :=")
        else:
            out.append(f"(** The blocks of slice {k}, part of the function they open. *)")
            out.append(f"Definition hi_blocks_{k:02d} : list term :=")
        out.append("  [")
        for i, e in enumerate(elems):
            e = list(e)
            if i < len(elems) - 1:
                e[-1] += ";"
            out.extend(e)
        out.append("  ].")
        with open(f"{outdir}/HiAtexitCode{k:02d}.v", "w", encoding="utf-8") as f:
            f.write("\n".join(out) + "\n")

    items_files = [k for k, (kind, _) in enumerate(files, 1) if kind == "items"]
    out = []
    out.append("(** The checked module nanofil -O makes of rocq/glibc/hi_atexit.c")
    out.append(f"    linked with its {unit_count} user glibc units by rocq/scripts/link.pl --ctors,")
    out.append(f"    as a [term]: the items of the slices HiAtexitCode01.v to HiAtexitCode{n:02d}.v")
    out.append("    in order. Generated by rocq/glibc/hi_atexit/code.sh, which checks it")
    out.append("    is current. Do not edit. *)")
    out.append("")
    out.append("From Stdlib Require Import String List.")
    out.append("From Nanofil Require Import Term.")
    out.append("From Glibc Require Import " + " ".join(f"HiAtexitCode{k:02d}" for k in items_files) + ".")
    out.append("Import ListNotations.")
    out.append("Open Scope string_scope.")
    out.append("")
    out.append("(** The module term. *)")
    out.append("Definition hi_atexit_term : term :=")
    out.append('  TApp "module" [TList (' + " ++ ".join(f"hi_items_{k:02d}" for k in items_files) + ")].")
    with open(f"{outdir}/HiAtexitTerm.v", "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(n)


def render_getopt(files, destination):
    header = [
        "(** This file contains part of glibc's checked option-parser module.",
        "    getopt/code.sh regenerates it from the pinned capture. Do not edit. *)",
        "", "From Stdlib Require Import String ZArith List Ascii.",
        "From Nanofil Require Import Term.",
    ]
    for k, (kind, elements) in enumerate(files, 1):
        uses = sorted(set(re.findall(r"getopt_blocks_(\d+)", str(elements))))
        out = header.copy()
        if uses:
            out.append("From Glibc Require Import " + " ".join(f"GetoptCode{n}" for n in uses) + ".")
        out += ["Import ListNotations.", "Open Scope string_scope.", "Open Scope Z_scope.",
                "", "(** Character atoms retain their byte values. *)",
                "Definition chr (n : nat) : term := TAtom (String (ascii_of_nat n) EmptyString).",
                "", f"(** These {kind} retain their order in the linked module. *)",
                f"Definition getopt_{kind}_{k:02} : list term :=", "  ["]
        for j, element in enumerate(elements):
            out += element[:-1] + [element[-1] + (";" if j + 1 < len(elements) else "")]
        out += ["  ]."]
        assert len(out) <= 700
        pathlib.Path(destination, f"GetoptCode{k:02}.v").write_text("\n".join(out) + "\n")
    ns = [f"{k:02}" for k, (kind, _) in enumerate(files, 1) if kind == "items"]
    out = header + ["From Glibc Require Import " + " ".join(f"GetoptCode{n}" for n in ns) + ".",
                    "Import ListNotations.", "Open Scope string_scope.", "",
                    "(** The linked module joins every generated item without changing its order. *)",
                    "Definition getopt_term : term :=",
                    '  TApp "module" [TList (' + " ++ ".join(f"getopt_items_{n}" for n in ns) + ")]."]
    pathlib.Path(destination, "GetoptTerm.v").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:])
