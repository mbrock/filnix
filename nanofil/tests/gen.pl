/*  Random integer IR functions with run/2 facts, printed as IR text
    (src/ir_text.pl).

    Run from nanofil/src:
      ../bin/nanofil --script ../tests/gen.pl SEED COUNT > gen.ir

    Each function mixes straight-line integer ops at both classes, an
    optional diamond with a phi, an optional counted loop, and an
    optional round trip through stack memory. Inputs favour edge values
    where signed, unsigned and width-dependent semantics differ.

    The functions are IR terms (ir.pl) valid by construction: the
    instruction shapes are the solutions of ir.pl's relations
    (op_kind/2, op_result_ok/3, op_arg_classes/4), and an operand is a
    temporary that dominates the use and may be read at the class the
    shape asks for, or a constant. Each function is still checked with
    valid_module/1 before it is printed.

    Randomness is a splitmix64 stream in Prolog, so a seed gives the same
    corpus on SWI and Trealla. The generator state g(Rng, N, Pool) holds
    the stream, the temporary counter and the pool of Name-Class
    temporaries an operand may read, and is threaded through the DCGs,
    which describe instruction and block lists, as two extra arguments.
*/
:- use_module('../src/ir').
:- use_module('../src/ir_text').
:- use_module(library(lists)).
:- use_module(library(dcgs)).
:- use_module(library(format)).

:- initialization(main).

main :-
    current_prolog_flag(argv, Argv),
    maplist(arg_integer, Argv, [Seed, Count]),
    format("% generated by gen.pl ~d ~d~n~n", [Seed, Count]),
    Count1 is Count - 1,
    catch(( numlist(0, Count1, Is),
            foldl(print_function, Is, Seed, _) ),
          E,
          ( format(user_error, "gen.pl: ~q~n", [E]), halt(1) )),
    halt(0).

% Trealla gives argv as character lists, SWI as atoms.
arg_integer(A, N) :- atom(A), !, atom_number(A, N).
arg_integer(Cs, N) :- number_chars(N, Cs).

% print_function(+I, +Rng0, -Rng): print the runs and the function gI.
print_function(I, Rng0, Rng) :-
    format(atom(Name), "g~d", [I]),
    function(Name, Func, Runs, g(Rng0, 0, []), g(Rng, _, _)),
    valid_module(module([Func])),
    maplist(print_run, Runs),
    print_module(module([Func])),
    nl.

print_run(Run) :-
    phrase(item_text(Run), Cs),
    format("~s.~n", [Cs]).

%% The shape of a function

% function(+Name, -Func, -Runs, +S0, -S): Func is a random function
% Name, and Runs are six calls of it.
function(Name, func(Name, export, Ret, Params, Blocks), Runs, S0, S) :-
    between_(1, 3, NP, S0, S1),
    NP1 is NP - 1,
    numlist(0, NP1, Ps),
    foldl(param, Ps, Params, S1, S2),
    choose([w, l], Ret, S2, S3),
    phrase(blocks(Ret, S3, S4), Blocks),
    length(Runs, 6),
    foldl(run(Name, Params), Runs, S4, S).

% param(+I, -Param, +S0, -S): the parameter pI, of a random class, joins
% the pool.
param(I, param(K, tmp(T)), S0, S) :-
    format(atom(T), "p~d", [I]),
    choose([w, l], K, S0, S1),
    S1 = g(R, N, Pool),
    S = g(R, N, [T-K|Pool]).

% blocks(+Ret, +S0, -S)//: the blocks of a function returning Ret: the
% entry block, maybe a diamond, maybe a loop, and a block that returns.
blocks(Ret, S0, S) -->
    { phrase(entry(S0, S1), Is0) },
    { chance(50, Diamond, S1, S2) },
    (   { Diamond == true }
    ->  diamond(Ret, start, [], Is0, L0, Phis0, S2, S3),
        { Is1 = [] }
    ;   { L0 = start, Phis0 = [], Is1 = Is0, S3 = S2 }
    ),
    { chance(40, Loop, S3, S4) },
    (   { Loop == true }
    ->  loop(Ret, L0, Phis0, Is1, S4, S5),
        { L = exit, Phis = [], Is = [] }
    ;   { L = L0, Phis = Phis0, Is = Is1, S5 = S4 }
    ),
    { operand(Ret, V, S5, S) },
    [block(L, Phis, Is, ret(V))].

% entry(+S0, -S)//: the entry block's instructions: maybe a round trip
% through memory, then two to eight ops.
entry(S0, S) -->
    { chance(40, Memory, S0, S1) },
    (   { Memory == true } -> memory(S1, S2) ; { S2 = S1 } ),
    { between_(2, 8, N, S2, S3) },
    ops(N, S3, S).

% diamond(+Ret, +L, +Phis, +Is, -Join, -JoinPhis, +S0, -S)//: block L
% (with Phis and Is) branches to two arms of one to three ops each,
% which meet at Join, whose phi of class Ret picks a value from each.
% Temporaries an arm defines leave the pool when it ends.
diamond(Ret, L, Phis, Is, join, [phi(tmp(J), Ret, [then-VT, else-VE])], S0, S) -->
    { operand(w, C, S0, S1) },
    [block(L, Phis, Is, branch(C, then, else))],
    arm(then, Ret, VT, S1, S2),
    arm(else, Ret, VE, S2, S3),
    { fresh(Ret, J, S3, S) }.

arm(L, Ret, V, S0, S) -->
    { S0 = g(_, _, Pool),
      between_(1, 3, N, S0, S1),
      phrase(ops(N, S1, S2), Is),
      operand(Ret, V, S2, g(R, M, _)),
      S = g(R, M, Pool) },
    [block(L, [], Is, goto(join))].

% loop(+Ret, +L, +Phis, +Is, +S0, -S)//: block L ends by computing a trip
% count of 0 to 7 and entering a loop that folds an accumulator of class
% Ret, which leaves the loop for exit at least once round. The folded
% value joins the pool.
loop(Ret, L, Phis, Is0, S0, S) -->
    { operand(w, C0, S0, S1),
      fresh(w, N, S1, S2),
      operand(Ret, Init, S2, S3),
      append(Is0, [let(tmp(N), w, and, [C0, const(7)])], Is),
      fresh_hidden(I, S3, S4), fresh_hidden(I1, S4, S5),
      fresh_hidden(A, S5, S6), fresh_hidden(C, S6, S7),
      fresh_hidden(A1, S7, S8),
      choose([add, mul, xor, sub], Op, S8, S9),
      operand(Ret, X, S9, g(R, M, Pool)),
      S = g(R, M, [A1-Ret|Pool]) },
    [block(L, Phis, Is, goto(loop)),
     block(loop, [phi(tmp(I), w, [L-const(0), loop-tmp(I1)]),
                phi(tmp(A), Ret, [L-Init, loop-tmp(A1)])],
         [let(tmp(A1), Ret, Op, [tmp(A), X]),
          let(tmp(I1), w, add, [tmp(I), const(1)]),
          let(tmp(C), w, cmp(slt, w), [tmp(I1), tmp(N)])],
         branch(tmp(C), loop, exit))].

%% Straight-line ops

ops(0, S, S) --> !.
ops(N, S0, S) --> op(S0, S1), { N1 is N - 1 }, ops(N1, S1, S).

% op(+S0, -S)//: one integer instruction. Its group is drawn with the
% weights gen.py had, then its op and classes uniformly among the group's
% shapes.
op(S0, S) -->
    { weighted([60-binary, 15-cmp, 15-ext, 10-neg], G, S0, S1),
      findall(Op-K, shape(G, Op, K), Shapes),
      choose(Shapes, Op-K, S1, S2),
      op_arg_classes(Op, K, plain, Cs),
      foldl(operand, Cs, Args, S2, S3),
      fresh(K, D, S3, S) },
    [let(tmp(D), K, Op, Args)].

% shape(?Group, ?Op, ?K): Op of Group may produce class K in a plain
% module from integer operands.
shape(G, Op, K) :-
    kind_group(Kind, G),
    op_kind(Op, Kind),
    member(K, [w, l]),
    op_result_ok(plain, Op, K),
    op_arg_classes(Op, K, plain, Cs),
    maplist(int_class, Cs).

kind_group(additive, binary).
kind_group(alu, binary).
kind_group(shift, binary).
kind_group(cmp, cmp).
kind_group(ext, ext).
kind_group(neg, neg).

int_class(w).
int_class(l).

%% A round trip through memory

% memory(+S0, -S)//: a 16-byte slot, initialised whole so every load is
% defined, then one to three stores and one to three loads at random
% widths and offsets. Addresses stay out of the pool: their values
% differ between the interpreter and native code.
memory(S0, S) -->
    { fresh_hidden(P, S0, S1), operand(l, V0, S1, S2),
      fresh_hidden(Q, S2, S3), operand(l, V8, S3, S4) },
    [let(tmp(P), l, alloc(8), [const(16)]),
     store(l, V0, tmp(P)),
     let(tmp(Q), l, add, [tmp(P), const(8)]),
     store(l, V8, tmp(Q))],
    { between_(1, 3, NS, S4, S5) },
    stores(NS, P, S5, S6),
    { between_(1, 3, NL, S6, S7) },
    loads(NL, P, S7, S).

stores(0, _, S, S) --> !.
stores(N, P, S0, S) -->
    { findall(W-VK, store_width(W, VK), Ws),
      choose(Ws, W-VK, S0, S1),
      width_bytes(W, Size),
      offset(Size, Off, S1, S2),
      fresh_hidden(A, S2, S3),
      operand(VK, V, S3, S4),
      N1 is N - 1 },
    [let(tmp(A), l, add, [tmp(P), const(Off)]), store(W, V, tmp(A))],
    stores(N1, P, S4, S).

% store_width(?W, ?K): an integer store of width W reads its value at K.
store_width(b, w).
store_width(h, w).
store_width(w, w).
store_width(l, l).

loads(0, _, S, S) --> !.
loads(N, P, S0, S) -->
    { findall(T-K, ( int_class(K), op_result_ok(plain, load(T), K) ), Ts),
      choose(Ts, T-K, S0, S1),
      load_bytes(T, Size),
      offset(Size, Off, S1, S2),
      fresh_hidden(A, S2, S3),
      fresh(K, D, S3, S4),
      N1 is N - 1 },
    [let(tmp(A), l, add, [tmp(P), const(Off)]), let(tmp(D), K, load(T), [tmp(A)])],
    loads(N1, P, S4, S).

load_bytes(T, Size) :- narrow_type(T, Size, _), !.
load_bytes(T, Size) :- width_bytes(T, Size).

% offset(+Size, -Off, +S0, -S): Size bytes at Off fit in the slot.
offset(Size, Off, S0, S) :-
    Max is 16 - Size,
    between_(0, Max, Off, S0, S).

%% Values

% operand(+K, -V, +S0, -S): V may be read at class K: mostly a
% temporary from the pool, else a constant.
operand(K, V, S0, S) :-
    S0 = g(_, _, Pool),
    findall(tmp(T), ( member(T-TK, Pool), reads_as(TK, K) ), Ts),
    chance(80, Temp, S0, S1),
    (   Ts \== [], Temp == true
    ->  choose(Ts, V, S1, S)
    ;   constant(V, S1, S)
    ).

% reads_as(?TK, ?K): a temporary of class TK may be read at class K.
reads_as(w, w).
reads_as(l, w).
reads_as(l, l).

constant(const(N), S0, S) :-
    chance(50, Edge, S0, S1),
    (   Edge == true
    ->  edges(Es), choose(Es, N, S1, S)
    ;   between_(-1000, 1000, N, S1, S)
    ).

% run(+Name, +Params, -Run, +S0, -S): a call of Name with an argument per
% parameter, mostly edge values, else anything from -2^63 to 2^64-1.
run(Name, Params, run(Name, Args), S0, S) :-
    foldl(argument, Params, Args, S0, S).

argument(_, N, S0, S) :-
    chance(70, Edge, S0, S1),
    (   Edge == true
    ->  edges(Es), choose(Es, N, S1, S)
    ;   Lo is -(1 << 63), Hi is (1 << 64) - 1,
        between_(Lo, Hi, N, S1, S)
    ).

edges([0, 1, 2, 3, 7, 31, 32, 33, 63, 64, 65, 127, 128, 255, 256,
       32767, 32768, 65535, 2147483647, 2147483648, 4294967295,
       4294967296, 9223372036854775807, 9223372036854775808,
       18446744073709551615, -1, -2, -128, -32768, -2147483648]).

%% Temporaries

% fresh(+K, -T, +S0, -S): T is a new temporary of class K in the pool.
fresh(K, T, g(R, N0, Pool), g(R, N, [T-K|Pool])) :-
    N is N0 + 1,
    format(atom(T), "t~d", [N]).

% fresh_hidden(-T, +S0, -S): T is a new temporary outside the pool.
fresh_hidden(T, g(R, N0, Pool), g(R, N, Pool)) :-
    N is N0 + 1,
    format(atom(T), "t~d", [N]).

%% Seeded choice

% chance(+P, -B, +S0, -S): B is true with probability P percent, else
% false. The draw is made either way, so the stream does not depend on
% how the caller branches.
chance(P, B, S0, S) :-
    between_(0, 99, X, S0, S),
    (   X < P -> B = true ; B = false ).

% choose(+Xs, -X, +S0, -S): X is an element of Xs, uniformly.
choose(Xs, X, S0, S) :-
    length(Xs, N),
    Hi is N - 1,
    between_(0, Hi, I, S0, S),
    nth0(I, Xs, X).

% weighted(+Ws, -X, +S0, -S): X is drawn from the W-X pairs of Ws with
% probability proportional to W.
weighted(Ws, X, S0, S) :-
    foldl(add_weight, Ws, 0, Total),
    Hi is Total - 1,
    between_(0, Hi, R, S0, S),
    pick_weighted(Ws, R, X).

add_weight(W-_, T0, T) :- T is T0 + W.

pick_weighted([W-Y|Ws], R, X) :-
    (   R < W -> X = Y
    ;   R1 is R - W, pick_weighted(Ws, R1, X)
    ).

% between_(+Lo, +Hi, -X, +S0, -S): X is drawn from Lo..Hi. Two 64-bit
% draws make the bias negligible for any range up to 2^64.
between_(Lo, Hi, X, g(R0, N, P), g(R, N, P)) :-
    splitmix64(R0, R1, A),
    splitmix64(R1, R, B),
    X is Lo + ((A << 64) \/ B) mod (Hi - Lo + 1).

% splitmix64(+S0, -S, -X): X is the next output of the stream S0.
splitmix64(S0, S, X) :-
    S is (S0 + 0x9E3779B97F4A7C15) mod (1 << 64),
    Z1 is (xor(S, S >> 30) * 0xBF58476D1CE4E5B9) mod (1 << 64),
    Z2 is (xor(Z1, Z1 >> 27) * 0x94D049BB133111EB) mod (1 << 64),
    X is xor(Z2, Z2 >> 31).
